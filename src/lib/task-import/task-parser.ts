export interface ParsedTask {
  date: Date;
  title: string;
}

const MONTHS = ['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];

function getMonthIndex(monthStr: string): number {
  const m = monthStr.toLowerCase().substring(0, 3);
  return MONTHS.indexOf(m);
}

function createLocalDate(year: number, monthIndex: number, day: number): Date {
  const d = new Date(year, monthIndex, day);
  d.setHours(0, 0, 0, 0);
  return d;
}

export function parseScheduleText(text: string): ParsedTask[] {
  const lines = text.split(/\r?\n/).map(l => l.trim()).filter(l => l.length > 0);
  const tasks: ParsedTask[] = [];
  let currentDate: Date | null = null;
  
  // Pattern 1: DD Month YYYY (e.g., 25 August 2026, 25 Aug 2026, 25-Aug-2026)
  const datePattern1 = /^(\d{1,2})[\s\-/]+([a-zA-Z]+)[\s\-/]+(\d{4})$/;
  // Pattern 2: Month DD, YYYY (e.g., August 25, 2026, Aug 25 2026)
  const datePattern2 = /^([a-zA-Z]+)\s+(\d{1,2})(?:st|nd|rd|th)?,?\s+(\d{4})$/;
  // Pattern 3: DD/MM/YYYY or DD-MM-YYYY (Strict DD/MM/YYYY assumption)
  const datePattern3 = /^(\d{1,2})[\s\-/]+(\d{1,2})[\s\-/]+(\d{4})$/;
  
  for (const line of lines) {
    // Ignore common non-task lines
    if (/^page\s+\d+/i.test(line)) continue;
    if (line.toLowerCase() === 'schedule' || line.toLowerCase() === 'timetable') continue;
    
    let parsedDate: Date | null = null;
    
    const m1 = line.match(datePattern1);
    if (m1) {
      const day = parseInt(m1[1], 10);
      const monthIdx = getMonthIndex(m1[2]);
      const year = parseInt(m1[3], 10);
      if (monthIdx !== -1 && day >= 1 && day <= 31) {
        parsedDate = createLocalDate(year, monthIdx, day);
      }
    } else {
      const m2 = line.match(datePattern2);
      if (m2) {
        const monthIdx = getMonthIndex(m2[1]);
        const day = parseInt(m2[2], 10);
        const year = parseInt(m2[3], 10);
        if (monthIdx !== -1 && day >= 1 && day <= 31) {
          parsedDate = createLocalDate(year, monthIdx, day);
        }
      } else {
        const m3 = line.match(datePattern3);
        if (m3) {
          const day = parseInt(m3[1], 10);
          const month = parseInt(m3[2], 10);
          const year = parseInt(m3[3], 10);
          if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
            parsedDate = createLocalDate(year, month - 1, day);
          }
        }
      }
    }
    
    if (parsedDate && !isNaN(parsedDate.getTime())) {
      currentDate = parsedDate;
      continue;
    }
    
    // If not a date line, and we have a current date, treat as a task
    if (currentDate) {
      tasks.push({
        date: new Date(currentDate.getTime()), // clone
        title: line
      });
    }
  }
  
  return tasks;
}

export interface ParsedTableTask {
  date: Date;
  title: string;
  description: string;
}

export function parseTableScheduleText(text: string): ParsedTableTask[] {
  const lines = text.split(/\r?\n/).map(l => l.trim()).filter(l => l.length > 0);
  const tasks: ParsedTableTask[] = [];
  
  let currentBaseDate: Date | null = null;
  let currentTaskTitle: string | null = null;
  let currentTaskDesc: string[] = [];
  let currentSlotIndex = 0; // 0 to 3
  
  const SLOTS = [9, 11, 14, 16]; // 09:00, 11:00, 14:00, 16:00
  
  // Known subject headers that indicate a new cell
  const KNOWN_HEADERS = new Set([
    "Quantitative Aptitude",
    "Reasoning Ability",
    "English Language",
    "Computer/Mock",
    "Data Analysis & DI",
    "General Awareness",
    "Banking Awareness",
    "SBI Clerk Mock",
    "Revision",
    "Reasoning",
    "Relaxation",
    "EXAM DAY",
    "Analysis",
    "Rest",
    "-",
    "Computer",
    "Strategy",
    "General Tamil/English",
    "Aptitude & Mental",
    "General Studies",
    "TN Development & GS",
    "TNPSC Revision"
  ]);

  const commitTask = () => {
    if (currentBaseDate && currentTaskTitle && currentSlotIndex < 4) {
      const taskDate = new Date(currentBaseDate);
      taskDate.setHours(SLOTS[currentSlotIndex], 0, 0, 0);
      tasks.push({
        date: taskDate,
        title: currentTaskTitle,
        description: currentTaskDesc.join('\n').trim()
      });
      currentSlotIndex++;
    }
  };

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    
    // Ignore page headers/footers
    if (/^page\s+\d+/i.test(line)) continue;
    if (line.includes("2026 COMPETITIVE EXAMS INTEGRATED STUDY PLAN")) continue;
    if (line.includes("60-DAY STRATEGIC PLAN")) continue;
    if (line.includes("Generated by Gemini Notebook")) continue;
    if (line.startsWith("WEEK ")) continue;
    if (line.startsWith("Date / Day")) continue;
    if (line.startsWith("10:30)")) continue;
    if (line === "- 12:30)") continue;
    if (line === "15:30)") continue;
    if (line === "(16:00 - 17:30)") continue;

    // Check for Date start e.g. "Sep 01 (Day"
    const dateMatch = line.match(/^([A-Z][a-z]{2})\s+(\d{1,2})\s+\(Day$/);
    if (dateMatch && i + 1 < lines.length && /^\d+\)$/.test(lines[i + 1])) {
      // It's a new date cell!
      commitTask(); // commit any pending task
      
      const monthStr = dateMatch[1];
      const day = parseInt(dateMatch[2], 10);
      const monthIdx = getMonthIndex(monthStr);
      if (monthIdx !== -1) {
        currentBaseDate = createLocalDate(2026, monthIdx, day);
        currentSlotIndex = 0;
        currentTaskTitle = null;
        currentTaskDesc = [];
      }
      i++; // skip the "01)" line
      continue;
    }
    
    // Also check for Date start e.g. "Oct 31 (Day" where maybe Day number is different, handled by \d+

    // Check if line is a known subject header
    if (KNOWN_HEADERS.has(line)) {
      if (currentTaskTitle) {
        commitTask();
      }
      currentTaskTitle = line;
      currentTaskDesc = [];
      continue;
    }

    // If we have a current task being built, add this line to description
    if (currentTaskTitle && currentBaseDate && currentSlotIndex < 4) {
      currentTaskDesc.push(line);
    }
  }
  
  // Commit the final task
  commitTask();
  
  return tasks;
}
